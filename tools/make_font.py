#!/usr/bin/env python3
"""Subset DejaVu Sans Bold to Latin + Cyrillic and emit src/font_data.h.

Usage: python3 tools/make_font.py /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf
Requires: pip install fonttools
"""
import io
import sys
from fontTools import subset
from fontTools.ttLib import TTFont

src = sys.argv[1]
unicodes = list(range(0x20, 0x7F)) + list(range(0x400, 0x460)) + list(range(0x490, 0x492)) + \
    [0xAB, 0xB0, 0xB2, 0xB7, 0xBB, 0xD7, 0x2013, 0x2014, 0x2019, 0x2026, 0x02BC, 0x2190, 0x2192]
font = TTFont(src)
opts = subset.Options()
opts.layout_features = []
opts.hinting = False
opts.drop_tables += ["GSUB", "GPOS", "GDEF", "kern"]
sub = subset.Subsetter(opts)
sub.populate(unicodes=unicodes)
sub.subset(font)
buf = io.BytesIO()
font.save(buf)
data = buf.getvalue()

with open("src/font_data.h", "w") as f:
    f.write("// Generated by tools/make_font.py from DejaVu Sans Bold (Bitstream Vera / DejaVu license, free to embed).\n")
    f.write("#pragma once\n\n")
    f.write(f"static const unsigned int kFontDataSize = {len(data)};\n")
    f.write("static const unsigned char kFontData[] = {\n")
    for i in range(0, len(data), 20):
        f.write("    " + ",".join(str(b) for b in data[i:i + 20]) + ",\n")
    f.write("};\n")
print("font bytes:", len(data))
